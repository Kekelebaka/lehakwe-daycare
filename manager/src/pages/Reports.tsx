// ── Shared PDF helpers ──
function addBranding(doc: jsPDF, title: string, subtitle?: string) {
  const w = doc.internal.pageSize.getWidth();
  doc.setFillColor(BRAND.r, BRAND.g, BRAND.b);
  doc.rect(0, 0, w, 38, 'F');
  doc.setFillColor(255, 255, 255);
  doc.circle(20, 19, 10, 'F');
  doc.setTextColor(BRAND.r, BRAND.g, BRAND.b);
  doc.setFontSize(10);
  doc.setFont('helvetica', 'bold');
  doc.text('LD', 20, 22, { align: 'center' });
  doc.setTextColor(255, 255, 255);
  doc.setFontSize(16);
  doc.setFont('helvetica', 'bold');
  doc.text('LEHAKWE DAYCARE', 38, 15);
  doc.setFontSize(8);
  doc.setFont('helvetica', 'normal');
  doc.text('NPO 22910695 | 12625 Phase 6, Bloemside 9323 | 061 549 1701', 38, 22);
  doc.setFontSize(11);
  doc.setFont('helvetica', 'bold');
  doc.text(title, 38, 32);
  if (subtitle) {
    doc.setFontSize(8);
    doc.setFont('helvetica', 'normal');
    doc.text(subtitle, w - 14, 32, { align: 'right' });
  }
  doc.setTextColor(150, 150, 150);
  doc.setFontSize(7);
  doc.text('Generated by Ubuntu Town ECD OS | lehakwedaycare.co.za', 14, 288);
  doc.text(`Page ${doc.getNumberOfPages()}`, w - 14, 288, { align: 'right' });
  doc.setTextColor(0, 0, 0);
}

